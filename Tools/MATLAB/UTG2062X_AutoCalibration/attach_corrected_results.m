function results = attach_corrected_results(results, calibration, cfg)
%ATTACH_CORRECTED_RESULTS Apply component calibration and recompute metrics.

results.CorrectedH1Vpk_mV = apply_amplitude_calibration( ...
    results.MeasuredH1Vpk_mV, calibration);
results.CorrectedHAVpk_mV = apply_amplitude_calibration( ...
    results.MeasuredHAVpk_mV, calibration);
results.CorrectedHBVpk_mV = apply_amplitude_calibration( ...
    results.MeasuredHBVpk_mV, calibration);

rowCount = height(results);
results.CorrectedVpp_mV = nan(rowCount, 1);
results.CorrectedRms_mV = nan(rowCount, 1);
for k = 1:rowCount
    amplitudes = [results.CorrectedH1Vpk_mV(k), ...
        results.CorrectedHAVpk_mV(k), results.CorrectedHBVpk_mV(k)];
    orders = [1, results.OrderA(k), results.OrderB(k)];
    phases = [0, results.PhaseA_deg(k), results.PhaseB_deg(k)];
    [results.CorrectedVpp_mV(k), results.CorrectedRms_mV(k)] = ...
        compose_wave_metrics(amplitudes, orders, phases);
end

results.CorrectedVppError_mV = ...
    results.CorrectedVpp_mV - results.TargetVpp_mV;
results.CorrectedRmsError_mV = ...
    results.CorrectedRms_mV - results.TargetRms_mV;
results.CorrectedH1Error_mV = ...
    results.CorrectedH1Vpk_mV - results.TargetH1Vpk_mV;
results.CorrectedHAError_mV = ...
    results.CorrectedHAVpk_mV - results.TargetHAVpk_mV;
results.CorrectedHBError_mV = ...
    results.CorrectedHBVpk_mV - results.TargetHBVpk_mV;

voltageLimit = cfg.RequiredVoltageError_mV;
results.CorrectedPass = results.Success & ...
    abs(results.CorrectedVppError_mV) <= voltageLimit & ...
    abs(results.CorrectedRmsError_mV) <= voltageLimit & ...
    abs(results.FrequencyError_kHz * 1000) <= ...
        cfg.RequiredFrequencyErrorHz & ...
    abs(results.CorrectedH1Error_mV) <= voltageLimit & ...
    abs(results.CorrectedHAError_mV) <= voltageLimit & ...
    (results.OrderB == 0 | ...
        abs(results.CorrectedHBError_mV) <= voltageLimit) & ...
    results.CollectionTime_ms <= cfg.RequiredCompletionTime_ms;
end

